const root = require('node:path').resolve(__dirname, '..');
const { _electron: electron } = require(root + '/node_modules/@playwright/test');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const fixture = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'better-terminal-shell-switch-'));
const project = path.join(fixture, 'Project folder'); fs.mkdirSync(project);
fs.writeFileSync(path.join(fixture, 'state.json'), JSON.stringify({ settings: { confirmClose: true }, sessions: [{ name: '', direction: 'horizontal', ratio: .5, panes: [{ cwd: project, profile: 'powershell' }, { cwd: project, profile: 'powershell' }] }] }));
const env = { ...process.env, BETTER_TERMINAL_DATA_DIR: fixture }; delete env.ELECTRON_RUN_AS_NODE;
let app, page;
const wait = async fn => { for (let i = 0; i < 150; i++) { if (await fn()) return; await new Promise(r => setTimeout(r, 100)); } throw new Error('Timed out waiting for shell'); };
const pane = i => page.locator('.terminal-pane').nth(i);
const run = async (i, command) => { await pane(i).locator('.xterm-helper-textarea').focus(); await page.keyboard.insertText(command); await page.keyboard.press('Enter'); };
(async () => {
  app = await electron.launch({ executablePath: process.env.BT_PACKAGED_EXE || undefined, args: process.env.BT_PACKAGED_EXE ? [] : [root], cwd: root, env });
  page = await app.firstWindow(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.waitForSelector('.terminal-pane');
  await wait(async () => (await pane(1).innerText()).includes('PS '));
  const original = await pane(0).getAttribute('data-pane-id');
  const other = await pane(1).getAttribute('data-pane-id');
  await page.getByLabel('Shell for terminal 1', { exact: true }).selectOption('cmd');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await pane(0).getAttribute('data-pane-id'), original);
  assert.equal(await page.getByLabel('Shell for terminal 1', { exact: true }).inputValue(), 'powershell');
  await page.getByLabel('Shell for terminal 1', { exact: true }).selectOption('cmd');
  await page.getByRole('button', { name: 'Change shell', exact: true }).click();
  await wait(async () => await page.getByLabel('Shell for terminal 1', { exact: true }).inputValue() === 'cmd');
  await wait(async () => (await pane(0).innerText()).includes('Microsoft Windows'));
  await run(0, 'echo SWITCH_OK & cd');
  await wait(async () => /(?:^|\n)SWITCH_OK\s*(?:\n|$)/.test(await pane(0).innerText()));
  assert.equal(await page.locator('.breadcrumb span').getAttribute('title'), project);
  assert.equal(await pane(1).getAttribute('data-pane-id'), other);
  await run(1, "Write-Output 'OTHER_PANE_OK'");
  await wait(async () => (await pane(1).innerText()).includes('OTHER_PANE_OK'));
  const text = await page.locator('body').innerText();
  assert.doesNotMatch(text, /A little less friction|A lot more flow|Room for your next idea|Pick up where you left off/);
  await page.setViewportSize({ width: 900, height: 580 });
  for (const i of [1, 2]) assert.equal(await page.getByLabel(`Shell for terminal ${i}`, { exact: true }).isVisible(), true);
  await page.screenshot({ path: path.join(fixture, 'shell-switch.png') });
  await page.getByLabel('Shell for terminal 1', { exact: true }).selectOption('powershell');
  await page.getByRole('button', { name: 'Change shell', exact: true }).click();
  await wait(async () => (await pane(0).innerText()).includes('PS '));
  await page.waitForTimeout(350);
  assert.equal((await page.evaluate(() => window.betterTerminal.bootstrap())).sessions[0].panes[0].profile, 'powershell');
  assert.deepEqual(errors, []);
  console.log('PASS: cancel preserves session; PowerShell/CMD switch in same folder; other pane remains live; selection persists; slogans removed; dropdown visible at minimum width.');
  console.log('SCREENSHOT', path.join(fixture, 'shell-switch.png'));
})().catch(async e => { console.error(e); if (page) console.error(await page.locator('body').innerText().catch(() => '')); process.exitCode = 1; }).finally(async () => {
  if (page) await page.evaluate(() => window.betterTerminal.updateSettings({ confirmClose: false })).catch(() => {});
  if (app) await app.close();
});
