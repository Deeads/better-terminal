const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = process.env.BT_PROJECT_ROOT || path.resolve(__dirname, '..');
const { _electron: electron } = require(path.join(root, 'node_modules/@playwright/test'));
const fixture = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'better-terminal-close-popup-'));
fs.writeFileSync(path.join(fixture, 'state.json'), JSON.stringify({ settings: { confirmClose: true }, sessions: [{ name: '', direction: 'horizontal', ratio: .5, panes: [{ cwd: fixture, profile: 'powershell' }] }] }));
const env = { ...process.env, BETTER_TERMINAL_DATA_DIR: fixture }; delete env.ELECTRON_RUN_AS_NODE;
let app, page;
const errors = [];
async function launch() {
  app = await electron.launch({ executablePath: process.env.BT_PACKAGED_EXE || undefined, args: process.env.BT_PACKAGED_EXE ? [] : [root], cwd: root, env });
  page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message));
  await page.waitForSelector('.terminal-pane');
  await page.waitForFunction(() => document.querySelector('.xterm-rows')?.textContent.includes('PS '));
  await app.evaluate(({ dialog }) => { dialog.showMessageBoxSync = () => { throw new Error('Native close dialog must not be used'); }; });
}
(async () => {
  await launch();
  const id = await page.locator('.terminal-pane').getAttribute('data-pane-id');
  await page.getByRole('button', { name: 'Close window', exact: true }).click();
  await page.getByRole('alertdialog', { name: 'Close Better Terminal?' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Keep open', exact: true }).evaluate(e => e === document.activeElement), true);
  await page.keyboard.press('Escape');
  await page.getByRole('alertdialog').waitFor({ state: 'detached' });
  assert.equal(await page.locator('.terminal-pane').getAttribute('data-pane-id'), id);
  await page.getByRole('button', { name: 'Settings', exact: false }).first().click();
  await app.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.close(); window.close(); });
  await page.getByRole('alertdialog').waitFor();
  assert.equal(await page.getByRole('alertdialog').count(), 1);
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.getByRole('button', { name: 'Close app', exact: true }).evaluate(e => e === document.activeElement), true);
  await page.keyboard.press('Tab');
  assert.equal(await page.getByRole('button', { name: 'Keep open', exact: true }).evaluate(e => e === document.activeElement), true);
  await page.screenshot({ path: path.join(fixture, 'close-popup.png') });
  await page.getByRole('button', { name: 'Keep open', exact: true }).click();
  await page.getByRole('dialog', { name: 'Settings', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await page.getByRole('button', { name: 'Close window', exact: true }).click();
  const closed = app.waitForEvent('close');
  await page.getByRole('button', { name: 'Close app', exact: true }).click();
  await closed; app = null;
  assert.equal(JSON.parse(fs.readFileSync(path.join(fixture, 'state.json'))).sessions[0].panes[0].cwd, fixture);
  await launch();
  await page.evaluate(() => window.betterTerminal.updateSettings({ confirmClose: false }));
  const disabledClosed = app.waitForEvent('close');
  await page.getByRole('button', { name: 'Close window', exact: true }).click();
  await disabledClosed; app = null;
  assert.deepEqual(errors, []);
  console.log('PASS: custom close popup, safe default focus, Escape and cancel, repeated/native close requests, focus trap over settings, saved layout, confirmed exit, confirmation setting.');
  console.log('SCREENSHOT', path.join(fixture, 'close-popup.png'));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { if (app) { await page.evaluate(() => window.betterTerminal.updateSettings({ confirmClose: false })).catch(() => {}); await app.close(); } });
